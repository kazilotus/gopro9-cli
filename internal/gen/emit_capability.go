package main

import (
	"fmt"
	"sort"
	"strings"
)

func emitCapability(m *model) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("%s", header)
	w("package capability\n\n")
	w("// SpecVersion is the Open GoPro HTTP spec version the matrix was generated from.\n")
	w("const SpecVersion = %q\n\n", m.SpecVersion)
	w("// FirmwareTested lists the HERO9 firmware versions the overrides were verified on.\n")
	w("var FirmwareTested = []string{")
	for i, f := range m.Firmware {
		if i > 0 {
			w(", ")
		}
		w("%q", f)
	}
	w("}\n\n")
	w("// Operations.\nconst (\n")
	for i := range m.Ops {
		o := &m.Ops[i]
		w("\t// %s: %s %s", o.Const, o.Method, o.Path)
		if o.Summary != "" {
			w(" — %s", o.Summary)
		}
		w("\n\t%s Op = %q\n", o.Const, o.ID)
	}
	w(")\n\n")
	w("var matrix = map[Op]Info{\n")
	for i := range m.Ops {
		o := &m.Ops[i]
		w("\t%s: {Op: %s, Method: %q, Path: %q, Summary: %q, Tags: %s, InSpec: %v, Legacy: %v, Level: %s, Note: %q},\n",
			o.Const, o.Const, o.Method, o.Path, o.Summary, goStrings(o.Tags), o.InSpec, o.Legacy, levelConst(o.Level), o.Note)
	}
	w("}\n")
	return b.String()
}

func goStrings(ss []string) string {
	if len(ss) == 0 {
		return "nil"
	}
	q := make([]string, len(ss))
	for i, s := range ss {
		q[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}

func levelConst(l string) string {
	switch l {
	case "verified":
		return "Verified"
	case "spec":
		return "Spec"
	default:
		return "Unsupported"
	}
}

func emitCapabilityDoc(m *model) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# HERO9 Black capability matrix\n\n")
	w("<!-- Generated by internal/gen from spec/opengopro/openapi.json + spec/hero9_overrides.yaml. DO NOT EDIT. -->\n\n")
	w("Open GoPro HTTP spec version **%s**. Overrides verified on firmware %s.\n\n", m.SpecVersion, strings.Join(m.Firmware, ", "))
	w("| Level | Meaning |\n|---|---|\n")
	w("| verified | Exercised against a real HERO9 over USB and behaves as documented |\n")
	w("| spec | Listed for HERO9 in the upstream spec; not yet exercised by this project |\n")
	w("| unsupported | Absent for HERO9 in the spec and/or returns 404/400 on this firmware |\n\n")
	ops := append([]opModel(nil), m.Ops...)
	sort.Slice(ops, func(i, j int) bool {
		if ops[i].Level != ops[j].Level {
			return levelRank(ops[i].Level) < levelRank(ops[j].Level)
		}
		return ops[i].ID < ops[j].ID
	})
	w("| Operation | Method | Path | Level | Note |\n|---|---|---|---|---|\n")
	for i := range ops {
		o := &ops[i]
		w("| `%s` | %s | `%s` | %s | %s |\n", o.ID, o.Method, o.Path, o.Level, strings.ReplaceAll(o.Note, "|", "\\|"))
	}
	w("\n## Settings (%d documented for HERO9)\n\nOptions marked `*` are documented by the spec but not listed for the HERO9; the camera may still report them.\n\n| ID | Name | Options |\n|---|---|---|\n", len(m.Settings))
	for _, s := range m.Settings {
		opts := make([]string, 0, len(s.Options))
		for _, o := range s.Options {
			mark := ""
			if !o.HERO9 {
				mark = "*"
			}
			opts = append(opts, fmt.Sprintf("%d=%s%s", o.Value, o.Label, mark))
		}
		if !s.IsEnum {
			if s.Max > 0 {
				opts = []string{fmt.Sprintf("integer %d–%d", s.Min, s.Max)}
			} else {
				opts = []string{"integer"}
			}
		}
		w("| %d | `%s` | %s |\n", s.ID, s.Name, strings.Join(opts, ", "))
	}
	w("\n## Statuses (%d documented, %d for HERO9)\n\n| ID | Name | Kind | HERO9 |\n|---|---|---|---|\n", len(m.Statuses), countHERO9(m.Statuses))
	for _, s := range m.Statuses {
		w("| %d | `%s` | %s | %v |\n", s.ID, kebab(s.Name), s.Kind, s.HERO9)
	}
	return b.String()
}

func levelRank(l string) int {
	switch l {
	case "verified":
		return 0
	case "spec":
		return 1
	default:
		return 2
	}
}

func countHERO9(ss []statusModel) int {
	n := 0
	for _, s := range ss {
		if s.HERO9 {
			n++
		}
	}
	return n
}
